    /** 이 플랫폼에서 보여줄 주제 — 다른 플랫폼 전용 주제·섹션·질문은 뺀다. */
    fun topicsFor(platform: Platform, visibleAreas: Set<Area>): List<Topic> =
        topics.filter { platform in it.platforms && it.area in visibleAreas }
            .map { t ->
                t.copy(
                    sections = t.sections.filter { platform in it.platforms },
                    faqs = t.faqs.filter { platform in it.platforms },
                    where = if (platform == Platform.DESKTOP) t.whereDesktop ?: t.where else t.where
                )
            }

    /** 검색어가 주제의 제목·요약·본문·질문 어디에든 있으면 true(대소문자·공백 무시). */
    fun matches(topic: Topic, query: String): Boolean {
        val q = query.trim().lowercase().replace(" ", "")
        if (q.isEmpty()) return true
        return searchableText(topic).contains(q)
    }

    private fun searchableText(topic: Topic): String = buildString {
        append(topic.title).append(topic.summary).append(topic.where)
        topic.sections.forEach { s ->
            append(s.heading)
            s.blocks.forEach { b ->
                when (b) {
                    is Block.Text -> append(b.text)
                    is Block.Steps -> b.items.forEach { append(it) }
                    is Block.Bullets -> b.items.forEach { append(it) }
                    is Block.Table -> b.rows.forEach { (k, v) -> append(k).append(v) }
                    is Block.Tip -> append(b.text)
                    is Block.Warn -> append(b.text)
                }
            }
        }
        topic.faqs.forEach { append(it.q).append(it.a) }
    }.lowercase().replace(" ", "")
}
