/**
 * 앱 내 도움말에 쓰이는 공용 텍스트. 실제 그림(모크업)은 플랫폼별 Compose 코드가 각자 그리므로 이
 * 파일엔 텍스트만 둔다 — MotivationalQuotes.kt/PersuasionMessages.kt와 같은 패턴.
 *
 * 97차 전면 개편: 89차엔 도움말이 "관리/일시정지/공부/루틴/모임/설정" 7페이지를 한 번에 스와이프하는
 * 단일 워크스루 하나뿐이었다. 93~96차에 디자인·기능이 계속 바뀌면서 그 내용이 실제 화면과 어긋나기
 * 시작했고, 태블릿에선 페이지 하나하나가 화면보다 커서 매번 스크롤해야 보이는 불편도 있었다. 이번에
 * 역할을 둘로 쪼갠다.
 * - [pages] (최초 실행 워크스루): "이 앱이 뭐고 어떻게 도움말을 다시 찾는지"만 짧게 2페이지로 안내 —
 *   개별 기능 상세는 아래 [TabGuideContent]로 옮겨서 여기선 더 이상 다루지 않는다.
 * - [TabGuideContent] (탭별 상세 도움말): 관리/공부/루틴/모임/설정 5개 탭 화면에 각각 ❓ 버튼으로
 *   달려있고, 그 탭에서 지금 볼 수 있는 기능을 작은 것까지 섹션별로 자세히 설명한다. 설정 탭에서도
 *   같은 내용을 탭별로 "다시 보기" 할 수 있다.
 *
 * 97차 2차 개편(사용자 피드백 "정보는 많은데 글만 있다"): 탭별 도움말을 한 화면에 다 몰아넣고 스크롤
 * 하는 방식에서, 워크스루처럼 섹션 하나당 페이지 하나로 나눠 넘기는 방식으로 바꾼다. 섹션마다 큰
 * 아이콘(원형 배지)을 붙여 글로만 채워지지 않게 한다 — 실제 스크린샷 파이프라인 없이 유지보수하기
 * 위해 여전히 이모지를 "이미지"로 쓰지만, 페이지를 쪼개고 아이콘을 키워 한 번에 읽을 정보량을 줄였다.
 */
data class GuidePage(
    val id: String,
    val emoji: String,
    val title: String,
    val bullets: List<String>,
)

