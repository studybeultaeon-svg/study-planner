// 강도 0(순한)~4(극한) — quoteForTier/confirmQuoteTier/blockQuoteTier가 이 인덱스를 공유한다.
const QUOTE_TIERS = [MILD_QUOTES, MEDIUM_QUOTES, SPICY_QUOTES, HARSH_QUOTES, EXTREME_QUOTES];

// 기존 코드 호환용(더 이상 직접 쓰지 않음) — tier 0(순한 맛) 전체.
const MOTIVATIONAL_QUOTES = MILD_QUOTES;

function quoteForTier(tier) {
  const t = Math.min(Math.max(tier, 0), QUOTE_TIERS.length - 1);
  const pool = QUOTE_TIERS[t];
  return pool[Math.floor(Math.random() * pool.length)];
}

// 실행확인 화면: 재확인 레벨(절대 수치, overlayLevelStepsToMax와 무관)이 높을수록 독한 문구.
function confirmQuoteTier(level) {
  if (level <= 1) return 0;
  if (level <= 3) return 1;
  if (level <= 5) return 2;
  if (level <= 7) return 3;
  return 4;
}

// 잠김(스케줄/일일한도) 화면: 오늘 이 그룹을 열려고 시도한 횟수가 많을수록 독한 문구.
function blockQuoteTier(attempts) {
  if (attempts <= 2) return 0;
  if (attempts <= 4) return 1;
  if (attempts <= 6) return 2;
  if (attempts <= 9) return 3;
  return 4;
}
